@app.route("/reset-password/<email>", methods=["GET", "POST"])
def reset_password(email):

    email = email.strip().lower()
    connection = get_database()

    user = connection.execute("""
        SELECT id, email, role
        FROM users
        WHERE email = %s
    """, (email,)).fetchone()

    if not user:
        connection.close()
        return "Account not found.", 404

