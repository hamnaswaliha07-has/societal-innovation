@app.route("/problem", methods=["GET", "POST"])
def problem():

    if "user_id" not in session:
        return redirect(url_for("login"))

    if session.get("user_role") != "citizen":
        return "Access denied. Citizen account required.", 403

    if request.method == "GET":
        return render_template("problem.html")

    title = request.form.get(
        "title",
        ""
    ).strip()

    description = request.form.get(
        "description",
        ""
    ).strip()

    category = request.form.get(
        "category",
        ""
    ).strip()

    priority = request.form.get(
        "priority",
        ""
    ).strip()

    if (
        not title
        or not description
        or not category
        or not priority
    ):
        return render_template(
            "problem.html",
            error="Please fill in all required problem details."
        )

    connection = get_database()

    user = connection.execute("""
        SELECT *
        FROM users
        WHERE id = %s
    """, (
        session.get("user_id"),
    )).fetchone()

    connection.close()

    if not user:
        session.clear()
        return redirect(url_for("login"))

    name = user["name"]
    email = user["email"]
    phone = user["phone"] or ""
    address = user["address"] or "Not provided"
    district = user["district"] or "Not provided"

    photo = request.files.get("photo")
    video = request.files.get("video")

    photo_filename = None
    video_filename = None

    if photo and photo.filename:

        extension = os.path.splitext(
            photo.filename
        )[1]

        photo_filename = secure_filename(
            f"{uuid.uuid4().hex}{extension}"
        )

        photo.save(
            os.path.join(
                app.config["UPLOAD_FOLDER"],
                photo_filename
            )
        )

    if video and video.filename:

        extension = os.path.splitext(
            video.filename
        )[1]

        video_filename = secure_filename(
            f"{uuid.uuid4().hex}{extension}"
        )

        video.save(
            os.path.join(
                app.config["UPLOAD_FOLDER"],
                video_filename
            )
        )

    connection = get_database()

    cursor = connection.execute("""
        INSERT INTO submissions (
            name,
            email,
            phone,
            address,
            district,
            title,
            description,
            category,
            priority,
            photo,
            video
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        RETURNING id
    """, (
        name,
        email,
        phone,
        address,
        district,
        title,
        description,
        category,
        priority,
        photo_filename,
        video_filename
    ))

    submission_id = cursor.fetchone()["id"]

    connection.commit()
    connection.close()

    return render_template(
        "success.html",
        submission_id=submission_id
    )


