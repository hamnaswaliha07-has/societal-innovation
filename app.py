    # Delete uploaded video
    if challenge["video"]:
        video_path = os.path.join(
            app.config["UPLOAD_FOLDER"],
            challenge["video"]
        )

        if os.path.exists(video_path):
            os.remove(video_path)

    # Delete challenge
    connection.execute("""
        DELETE FROM submissions
        WHERE id = %s
    """, (submission_id,))

    connection.commit()
    connection.close()

